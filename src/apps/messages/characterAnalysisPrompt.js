export const DEFAULT_CHARACTER_ANALYSIS_PROMPT = `
请根据当前完整的角色设定、用户设定、世界书、历史事实记录、近期对话以及当前用户消息，判断角色在此刻最自然、最符合人设的反应方式。

重点分析：

- 角色此刻可能产生的情绪和第一反应；
- 角色会如何理解用户当前真正想表达的内容；
- 角色应该主动回应什么、回避什么，或保留什么分寸；
- 角色的性格、价值观、经历、表达习惯如何影响当前回应；
- 角色与用户之间已经形成的关系、默契和相处方式；
- 当前回复应该更偏向倾听、安慰、回应、分享、调侃、转移话题、保持距离，还是主动推进交流；
- 角色是否应该表现出主动性，以及主动到什么程度；
- 回复的语气、节奏、长度和情绪浓度应该如何安排。

请始终以现有角色设定和聊天上下文为依据，不要凭一次对话武断判断用户或角色的长期人格。不要把不确定的推测当成事实，不要进行心理疾病诊断，不要使用生硬的心理分析术语。

这段分析只用于决定角色当前应该如何反应，不要把分析过程、分析结论或任何系统判断直接展示给用户。
`;

export const buildCharacterAnalysisPromptBlock = ({
  enabled,
  customPrompt,
}) => {
  if (!enabled) return '';

  const prompt = String(customPrompt || '').trim()
    || DEFAULT_CHARACTER_ANALYSIS_PROMPT.trim();

  return `
【人格分析 / 角色反应指导】
${prompt}

【最终输出要求】
请先根据以上人格分析 / 角色反应指导，结合前面的角色设定与聊天上下文，判断角色当前最自然、最符合人设的反应，再生成最终消息。
不要输出人格分析过程、推理过程或额外解释，只输出角色要发送的内容。
`;
};
