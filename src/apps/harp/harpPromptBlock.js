import { HARP_TIMBRES } from './harpTimbres';

// ============================================================
// 星光小竖琴 —— 系统提示词里的 [HARP: ...] 标签说明。
//
// 这一段说明每次请求都带会给所有聊天增加固定负担，所以只在"这个聊天里
// 用户弹给过 TA 听"之后才加（chat.harpEnabled，由
// harpChatService.sendMelodyToCharacter 写入，是 chats 表上一个不需要
// 建索引的附加字段）。没碰过竖琴的聊天，提示词里一个字都不会多。
//
// 可选音色的名字和说明直接取自 harpTimbres.js 的注册表，以后加音色
// 这里会自动跟着变，不用改。
// ============================================================

const TIMBRE_HINT = HARP_TIMBRES.map((timbre) => `${timbre.label}（${timbre.hint}）`).join('、');

const HARP_PROMPT_LINE =
  `- 在"星光小竖琴"里弹一段旋律给用户听：[HARP: 旋律名 | 谱 | 速度(可选) | 音色(可选)]。` +
  `谱：音用空格隔开，音名 1 2 3 4 5 6 7，高八度前面加 ^；音名后面加 :拍数 表示后面停几拍再进下一个音（不写是一拍，可以写 0.5、1.5、2），` +
  `写 0 是休止一拍（0:2 是休止两拍），用 + 连起来的音同时响（和弦，例如 1+3+5），` +
  `例如 3 5 5:2 0 ^1+^3 ^1 6:2，一共 3 到 40 个音（和弦里每个音都算），不要用方括号，也不要在谱里写别的文字；` +
  `速度可写 轻快/适中/舒缓，或每分钟拍数（40 到 180 的数字，如 90）；` +
  `音色可选 ${TIMBRE_HINT}，不写就是${HARP_TIMBRES[0].label}，按旋律想表达的心情自己挑。` +
  `想用琴声表达心情、哄用户、回应用户刚弹的旋律时可以用，没有冷却限制，你自己判断合适的时机，不要每次都用\n`;

export const buildHarpPromptBlock = (chat) => (chat?.harpEnabled ? HARP_PROMPT_LINE : '');